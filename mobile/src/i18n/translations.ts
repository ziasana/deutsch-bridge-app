export type AppLanguage = 'en' | 'fa';

/**
 * Same rule as the web app (frontend/lib/i18n/translations.ts): the account's explanation
 * language decides the interface language. Persian (PR) gets the Persian UI; EN, DE and
 * "not set yet" get English.
 */
export function toAppLanguage(
  preferred: PreferredLanguage | string | null | undefined,
): AppLanguage {
  return preferred === 'PR' ? 'fa' : 'en';
}

